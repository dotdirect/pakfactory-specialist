import fs from 'node:fs/promises'
import path from 'node:path'

const rootDir = process.cwd()
const skillsDir = path.join(rootDir, 'src/lib/prompts/skills')
const outputPath = path.join(skillsDir, 'generated.ts')

const sourceFiles = ['cs-agent.md', 'specialist-agent.md']

function asTemplateLiteral(value) {
  return `\`${value.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')}\``
}

async function readSkillSources() {
  const entries = []
  for (const fileName of sourceFiles) {
    const filePath = path.join(skillsDir, fileName)
    const raw = await fs.readFile(filePath, 'utf8')
    const varName = fileName
      .replace(/\.md$/i, '')
      .replace(/-([a-z])/g, (_, c) => c.toUpperCase())
      .replace(/^([a-z])/, (_, c) => c.toUpperCase()) + 'SkillMarkdown'

    entries.push({ fileName, raw, varName })
  }
  return entries
}

async function main() {
  const entries = await readSkillSources()
  const lines = []
  lines.push('// AUTO-GENERATED FILE. DO NOT EDIT DIRECTLY.')
  lines.push('// Generated by scripts/generate-prompt-skills.mjs.')
  lines.push('')

  for (const entry of entries) {
    lines.push(`/** Source: ${entry.fileName} */`)
    lines.push(`export const ${entry.varName} = ${asTemplateLiteral(entry.raw)}`)
    lines.push('')
  }

  lines.push('export const promptSkillMarkdownByName = {')
  for (const entry of entries) {
    const key = entry.fileName.replace(/\.md$/i, '')
    lines.push(`  '${key}': ${entry.varName},`)
  }
  lines.push('} as const')
  lines.push('')

  await fs.writeFile(outputPath, `${lines.join('\n')}\n`, 'utf8')
  process.stdout.write(`Wrote ${path.relative(rootDir, outputPath)}\n`)
}

main().catch((error) => {
  process.stderr.write(`${String(error)}\n`)
  process.exit(1)
})
